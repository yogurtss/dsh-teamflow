/** Start loop-preview.mjs with TEAMFLOW_PREVIEW_TEMPLATE=builtin-operator-loop. */
import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
const { chromium } = await import(process.env.TEAMFLOW_PLAYWRIGHT_MODULE ?? 'playwright')
const output=resolve('output/loop-layout-browser'); mkdirSync(output,{recursive:true})
const browser=await chromium.launch({channel:'msedge',headless:true})
try {
 const page=await browser.newPage({viewport:{width:1600,height:1050}}), errors=[]
 page.setDefaultTimeout(15000)
 page.on('pageerror',error=>errors.push(error.message))
 await page.goto(process.env.TEAMFLOW_LOOP_URL??'http://127.0.0.1:8384')
 await page.locator('[data-canvas-node="optimize"]').waitFor()
 if (await page.getByRole('button',{name:'收起右侧面板',exact:true}).count()) await page.getByRole('button',{name:'收起右侧面板',exact:true}).click()
 await page.getByRole('button',{name:'自动整理',exact:true}).click()
 await page.getByRole('button',{name:'适应画布',exact:true}).click()
 assert.equal(await page.locator('[data-loop-region]').count(),1)
 assert.equal(await page.locator('[data-flow-branch="pass"]').count(),1)
 assert.equal(await page.locator('[data-flow-branch="reject"]').count(),1)
 const before=await page.locator('[data-canvas-node]').evaluateAll(nodes=>Object.fromEntries(nodes.map(node=>[node.dataset.canvasNode,{x:parseFloat(node.style.left),y:parseFloat(node.style.top)}])))
 assert.ok(before['iteration-review'].y>before.optimize.y && before['iteration-review'].y>before.performance.y)
 await page.screenshot({path:resolve(output,'operator-canvas.png')})
 await page.reload();await page.locator('[data-canvas-node="optimize"]').waitFor()
 const persisted=await page.locator('[data-canvas-node]').evaluateAll(nodes=>Object.fromEntries(nodes.map(node=>[node.dataset.canvasNode,{x:parseFloat(node.style.left),y:parseFloat(node.style.top)}])))
 assert.deepEqual(persisted,before)
 await page.getByRole('button',{name:'流程模板库',exact:true}).click()
 for(const id of ['builtin-operator-loop','builtin-bugfix-loop']) {
  const card=page.locator(`[data-template-choice="view:${id}"]`);await card.waitFor()
  assert.equal(await card.locator('[data-flow-branch="pass"]').count(),1)
  assert.equal(await card.locator('[data-flow-branch="reject"]').count(),1)
  await card.screenshot({path:resolve(output,`${id}-card.png`)})
  await card.click()
  const preview=page.locator('svg[data-loop-preview]').last()
  await preview.waitFor()
  const visibleBranches=await preview.evaluate(svg=>{const bounds=svg.getBoundingClientRect();return [...svg.querySelectorAll('[data-flow-branch] text')].every(text=>{const box=text.getBoundingClientRect();return box.left>=bounds.left&&box.right<=bounds.right})})
  assert.ok(visibleBranches,'PASS and REJECT labels must both be visible without scrolling')
  const exitVisible=await preview.locator('[data-preview-node="delivery"]').evaluate(node=>{const svg=node.ownerSVGElement.getBoundingClientRect(),box=node.getBoundingClientRect();return box.left>=svg.left&&box.right<=svg.right&&box.bottom<=svg.bottom})
  assert.ok(exitVisible,'The pass destination must not be clipped')
  await preview.locator('..').screenshot({path:resolve(output,`${id}-detail.png`)})
  await page.getByRole('button',{name:'完整流程',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'完整流程',exact:true}).getAttribute('aria-pressed'),'true')
  await page.getByRole('button',{name:'← 所有模板',exact:true}).click()
 }
 await page.getByLabel('Preview language').selectOption('en')
 await page.emulateMedia({colorScheme:'dark'});await page.evaluate(()=>document.documentElement.style.colorScheme='dark')
 await page.setViewportSize({width:600,height:900})
 const card=page.locator('[data-template-choice="view:builtin-operator-loop"]');await card.screenshot({path:resolve(output,'operator-dark-en.png')})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false)
 assert.deepEqual(errors,[])
 writeFileSync(resolve(output,'result.json'),JSON.stringify({passed:true,errors,branches:['PASS','REJECT'],layoutPersists:true},null,2))
} finally {await browser.close()}
