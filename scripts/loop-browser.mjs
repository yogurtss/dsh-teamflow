/** Runs against loop-preview.mjs. Asserts real UI + backend state, with simulated model execution. */
import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
const { chromium } = await import(process.env.TEAMFLOW_PLAYWRIGHT_MODULE ?? 'playwright')
const human = process.env.TEAMFLOW_LOOP_MODE === 'human'
const output = resolve(human ? 'output/gated-loops-browser-human' : 'output/gated-loops-browser'); mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1050 } }), errors = [], requests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.url().endsWith('/workflow') && request.method() === 'POST') requests.push(request.postDataJSON()) })
  await page.goto(process.env.TEAMFLOW_LOOP_URL ?? 'http://127.0.0.1:8384')
  await page.locator('[data-canvas-node="gate"]').click()
  const panel = page.getByRole('region', { name: '门控循环', exact: true })
  await panel.getByLabel('回退入口', { exact: true }).selectOption('a')
  await panel.getByLabel('审核方式', { exact: true }).selectOption(human ? 'human' : 'ai')
  if (!human) await panel.getByLabel('独立审核成员', { exact: true }).selectOption('reviewer')
  await panel.getByLabel('轮次上限（包含首次）', { exact: true }).fill('2')
  await panel.getByRole('button', { name: '创建循环', exact: true }).click()
  await page.locator(`[data-canvas-node="gate"][data-gate-mode="${human ? 'human' : 'ai'}"]`).waitFor()
  await panel.getByRole('button', {name:'启动循环',exact:true}).waitFor()
  const gate = page.locator('[data-canvas-node="gate"]')
  assert.equal(await gate.getAttribute('data-node-shape'), 'decision')
  assert.equal(await gate.getAttribute('data-gate-mode'), human ? 'human' : 'ai')
  const ports = await gate.evaluate(node => {
    const card = node.getBoundingClientRect()
    return [...node.querySelectorAll('[data-connection-handle]')].map(port => { const r = port.getBoundingClientRect(); return { x: (r.left + r.width / 2 - card.left) / card.width, y: (r.top + r.height / 2 - card.top) / card.height } })
  })
  assert.ok(Math.abs(ports[0].x) < .01 && Math.abs(ports[1].x - 1) < .01)
  assert.ok(ports.every(p => Math.abs(p.y - .5) < .01), 'Decision ports must touch the diamond vertices')
  await page.getByRole('button', { name: '开始全部', exact: true }).click()
  const review = async (round, pass = false) => {
    await panel.getByText(new RegExp('审核中 · 第 ' + round + '/')).waitFor({timeout:20000})
    await panel.getByRole('button', {name:'读取本轮审核材料',exact:true}).click()
    await panel.getByLabel('审核意见、修改要求与复验条件', {exact:true}).fill(pass ? '验证已全部通过，可以交付。' : '补齐边界条件，并重新执行验证。')
    if (!pass) await panel.getByRole('checkbox', {name:'实现与验证',exact:true}).check()
    await panel.getByRole('button', {name: pass ? '通过并继续' : '按意见改进', exact:true}).click()
  }
  if (human) { await review(1); await review(2) }
  await panel.getByText('已达轮次上限，等待人工追加轮数或结束', { exact: true }).waitFor({ timeout: 20000 })
  assert.equal(await page.locator('[data-canvas-node]').count(), 4)
  assert.equal(await page.locator('[data-canvas-node="after"]').getAttribute('data-status'), 'pending')
  await panel.getByRole('button', { name: /查看多轮历史/ }).click()
  await panel.getByText('历史只读，按页加载。文件摘要不等于历史文件副本。', { exact: true }).waitFor()
  const historyRequestCount = requests.filter(r => r.action === 'loop_history').length
  await page.waitForTimeout(1500)
  assert.equal(requests.filter(r => r.action === 'loop_history').length, historyRequestCount, 'polling must not fetch history')
  await panel.locator('summary').filter({ hasText: /审核决定/ }).first().click()
  await panel.getByRole('button', { name: '固定此记录用于比较', exact: true }).first().click()
  await page.screenshot({ path: resolve(output, 'limit-and-history.png') })
  await panel.getByRole('button', { name: '更早记录', exact: true }).click()
  await panel.getByLabel('明确追加轮数', { exact: true }).fill('1')
  await panel.getByRole('button', { name: '继续循环', exact: true }).click()
  if (human) await review(3, true)
  await panel.getByText(/已通过 · 第 3\/3/).waitFor({ timeout: 20000 })
  assert.equal(await page.locator('[data-canvas-node]').count(), 4)
  await page.locator('[data-canvas-node="after"][data-status="completed"]').waitFor()
  await page.screenshot({ path: resolve(output, 'passed.png') })
  await page.getByLabel('Preview language').selectOption('en')
  await page.getByRole('region', { name: 'Gated loop', exact: true }).getByText(/Passed · Round 3\/3/).waitFor()
  await page.setViewportSize({ width: 600, height: 900 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.evaluate(() => { document.documentElement.style.colorScheme = 'dark' })
  await page.getByRole('button', { name: 'Changes and reviews', exact: true }).click()
  await page.getByRole('region', { name: 'Gated loop', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: resolve(output, 'narrow-dark-en.png') })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false)
  assert.deepEqual(errors, [])
  await page.setViewportSize({ width: 1500, height: 900 })
  await page.getByRole('button', { name: 'Hide right panel', exact: true }).click()
  await page.getByRole('button', { name: 'Fit to canvas', exact: true }).click()
  await page.screenshot({ path: resolve(output, 'decision-card-dark.png') })
  await page.emulateMedia({ colorScheme: 'light' })
  await page.evaluate(() => { document.documentElement.style.colorScheme = 'light' })
  await page.getByLabel('Preview language').selectOption('zh')
  await page.waitForTimeout(250)
  await page.screenshot({ path: resolve(output, 'decision-card-light.png') })
  writeFileSync(resolve(output, 'result.json'), JSON.stringify({ passed: true, errors, actions: requests.filter(r => r.action !== 'state').map(r => r.action), nodeCount: 4 }, null, 2))
} finally { await browser.close() }
